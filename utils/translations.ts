export function getLocalizedCurrency(code: string, fallbackName?: string, fallbackSymbol?: string, lang: LanguageKey = 'ar'): LocalizedCurrencyInfo {
  const normCode = (code || '').toUpperCase().trim();
  const entry = CURRENCY_DICTIONARY[normCode];
  if (entry) {
    const data = entry[lang] || entry.ar;
    return {
      code: normCode,
      name: data.name,
      symbol: data.symbol,
      badge: data.badge,
    };
  }
  return {
    code: normCode || 'SAR',
    name: fallbackName || normCode || (lang === 'ar' ? 'ريال سعودي' : 'Saudi Riyal'),
    symbol: fallbackSymbol || (lang === 'ar' ? 'ر.س' : 'SAR'),
  };
}
